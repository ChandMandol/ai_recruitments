from datetime import datetime, timezone
from typing import TYPE_CHECKING, List, Optional
from sqlalchemy import Boolean, DateTime, ForeignKey, Integer, JSON, String, Text
from sqlalchemy.orm import Mapped, mapped_column, relationship
from app.core.database import Base
from app.models.base import TimestampMixin, UUIDMixin

if TYPE_CHECKING:
    from app.models.application import JobApplication
    from app.models.job import Job
    from app.models.user import User


class SystemSetting(Base):
    """Platform-level dynamic settings (e.g., custom Gemini API Key configured via Admin Dashboard)."""
    __tablename__ = "system_settings"

    key: Mapped[str] = mapped_column(String(100), primary_key=True)
    value: Mapped[str] = mapped_column(Text, nullable=False)
    description: Mapped[str | None] = mapped_column(String(255), nullable=True)
    is_secret: Mapped[bool] = mapped_column(Boolean, default=False, nullable=False)
    updated_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        default=lambda: datetime.now(timezone.utc),
        onupdate=lambda: datetime.now(timezone.utc),
        nullable=False,
    )


class CVAnalysisReport(Base, UUIDMixin, TimestampMixin):
    """AI CV Analysis report generated by Google Gemini comparing candidate resume against job description."""
    __tablename__ = "cv_analysis_reports"

    application_id: Mapped[str] = mapped_column(
        String(36),
        ForeignKey("job_applications.id", ondelete="CASCADE"),
        unique=True,
        index=True,
        nullable=False,
    )
    job_id: Mapped[str] = mapped_column(
        String(36),
        ForeignKey("jobs.id", ondelete="CASCADE"),
        index=True,
        nullable=False,
    )
    candidate_id: Mapped[str] = mapped_column(
        String(36),
        ForeignKey("users.id", ondelete="CASCADE"),
        index=True,
        nullable=False,
    )

    overall_score: Mapped[int] = mapped_column(Integer, nullable=False)  # 0 to 100
    recommendation: Mapped[str] = mapped_column(String(50), nullable=False)
    recommendation_reason: Mapped[str] = mapped_column(Text, nullable=False)

    # Detailed extractions & comparisons
    extracted_profile: Mapped[dict] = mapped_column(JSON, default=dict, nullable=False)
    skill_matching: Mapped[dict] = mapped_column(JSON, default=dict, nullable=False)
    experience_matching: Mapped[dict] = mapped_column(JSON, default=dict, nullable=False)
    education_matching: Mapped[dict] = mapped_column(JSON, default=dict, nullable=False)
    strengths: Mapped[list] = mapped_column(JSON, default=list, nullable=False)
    weaknesses: Mapped[list] = mapped_column(JSON, default=list, nullable=False)
    suggested_questions: Mapped[list] = mapped_column(JSON, default=list, nullable=False)
    raw_cv_text_snippet: Mapped[str | None] = mapped_column(Text, nullable=True)

    analyzed_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        default=lambda: datetime.now(timezone.utc),
        nullable=False,
    )

    # Relationships
    application: Mapped["JobApplication"] = relationship("JobApplication", back_populates="analysis_report")
    job: Mapped["Job"] = relationship("Job")
    candidate: Mapped["User"] = relationship("User")

